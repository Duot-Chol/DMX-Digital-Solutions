import uuid
from decimal import Decimal

from django.core.validators import MinValueValidator
from django.db import models

from customers.models import Customer
from subscriptions.models import Subscription


class Payment(models.Model):
    """
    Records a payment transaction made by a DMX customer.

    Payment records preserve transaction history. A payment is not
    considered successful merely because a request was submitted.

    A payment may optionally be associated with an order or a
    subscription. Existing subscription payment workflows remain
    supported.
    """

    class PaymentMethod(models.TextChoices):
        BANK_TRANSFER = "BANK_TRANSFER", "Bank Transfer"
        MOBILE_MONEY = "MOBILE_MONEY", "Mobile Money"
        CARD = "CARD", "Card"
        CASH = "CASH", "Cash"
        OTHER = "OTHER", "Other"

    class Status(models.TextChoices):
        PENDING = "PENDING", "Pending"
        PROCESSING = "PROCESSING", "Processing"
        SUCCESSFUL = "SUCCESSFUL", "Successful"
        FAILED = "FAILED", "Failed"
        CANCELLED = "CANCELLED", "Cancelled"
        REFUNDED = "REFUNDED", "Refunded"

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    payment_reference = models.CharField(
        max_length=30,
        unique=True,
        editable=False,
        help_text="Unique payment reference generated by DMX Digital Solutions.",
    )

    customer = models.ForeignKey(
        Customer,
        on_delete=models.PROTECT,
        related_name="payments",
    )

    order = models.ForeignKey(
        "orders.Order",
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="payments",
        help_text="Optional order associated with this payment.",
    )

    subscription = models.ForeignKey(
        Subscription,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="payments",
        help_text="Optional subscription associated with this payment.",
    )

    amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(Decimal("0.01"))],
    )

    currency = models.CharField(
        max_length=3,
        default="USD",
    )

    payment_method = models.CharField(
        max_length=20,
        choices=PaymentMethod.choices,
    )

    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.PENDING,
        db_index=True,
    )

    external_transaction_reference = models.CharField(
        max_length=150,
        blank=True,
        help_text="Transaction reference supplied by a bank or payment provider.",
    )

    description = models.CharField(
        max_length=255,
        blank=True,
    )

    failure_reason = models.TextField(
        blank=True,
    )

    paid_at = models.DateTimeField(
        null=True,
        blank=True,
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    class Meta:
        verbose_name = "Payment"
        verbose_name_plural = "Payments"
        ordering = ("-created_at",)

    def __str__(self):
        return f"{self.payment_reference} - {self.amount} {self.currency}"


class PaymentNumberCounter(models.Model):
    """
    Stores the next payment reference number to allocate.
    """

    name = models.CharField(
        max_length=50,
        unique=True,
    )

    next_number = models.PositiveBigIntegerField(
        default=1,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    class Meta:
        verbose_name = "Payment Number Counter"
        verbose_name_plural = "Payment Number Counters"

    def __str__(self):
        return f"{self.name}: next number {self.next_number}"
