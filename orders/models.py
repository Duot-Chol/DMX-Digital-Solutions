import uuid
from decimal import Decimal

from django.conf import settings
from django.core.validators import MinValueValidator
from django.db import models


class Order(models.Model):
    """
    Represents a commercial order placed by a DMX customer.

    Payment status is derived from successful payments or,
    for zero-value orders, explicit staff approval.
    """

    class Status(models.TextChoices):
        DRAFT = "DRAFT", "Draft"
        CONFIRMED = "CONFIRMED", "Confirmed"
        PROCESSING = "PROCESSING", "Processing"
        FULFILLED = "FULFILLED", "Fulfilled"
        CANCELLED = "CANCELLED", "Cancelled"

    class PaymentStatus(models.TextChoices):
        UNPAID = "UNPAID", "Unpaid"
        PARTIALLY_PAID = "PARTIALLY_PAID", "Partially Paid"
        PAID = "PAID", "Paid"

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    order_number = models.CharField(
        max_length=30,
        unique=True,
        editable=False,
        help_text="Unique order reference generated by DMX Digital Solutions.",
    )

    customer = models.ForeignKey(
        "customers.Customer",
        on_delete=models.PROTECT,
        related_name="orders",
    )

    status = models.CharField(
        max_length=20,
        choices=Status.choices,
        default=Status.DRAFT,
        db_index=True,
    )

    currency = models.CharField(
        max_length=3,
        default="USD",
    )

    subtotal = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=Decimal("0.00"),
        validators=[MinValueValidator(Decimal("0.00"))],
    )

    notes = models.TextField(
        blank=True,
        help_text="Internal notes for authorized staff.",
    )

    free_order_approved_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="approved_free_orders",
        help_text="Staff member who approved this zero-value order.",
    )

    free_order_approved_at = models.DateTimeField(
        null=True,
        blank=True,
        help_text="Date and time when this zero-value order was approved.",
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    class Meta:
        verbose_name = "Order"
        verbose_name_plural = "Orders"
        ordering = ("-created_at",)

    def __str__(self):
        return self.order_number

    @property
    def payment_status(self):
        """
        Derive payment status without allowing manual editing.

        A zero-value order is considered paid only when both
        approval audit fields have been recorded.

        For paid orders, only successful payments associated
        with this order and using its currency are counted.
        """
        if self.subtotal == Decimal("0.00"):
            if (
                self.free_order_approved_by_id is not None
                and self.free_order_approved_at is not None
            ):
                return self.PaymentStatus.PAID

            return self.PaymentStatus.UNPAID

        from payments.models import Payment

        successful_total = (
            Payment.objects.filter(
                order_id=self.pk,
                status=Payment.Status.SUCCESSFUL,
                currency=self.currency,
            ).aggregate(
                total=models.Sum("amount")
            )["total"]
            or Decimal("0.00")
        )

        if successful_total <= Decimal("0.00"):
            return self.PaymentStatus.UNPAID

        if successful_total < self.subtotal:
            return self.PaymentStatus.PARTIALLY_PAID

        return self.PaymentStatus.PAID


class OrderItem(models.Model):
    """
    Represents one product or subscription plan purchased in an order.

    Exactly one of product or subscription_plan must be provided.
    Item descriptions and prices are historical snapshots.
    """

    id = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False,
    )

    order = models.ForeignKey(
        Order,
        on_delete=models.PROTECT,
        related_name="items",
    )

    product = models.ForeignKey(
        "products.Product",
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="order_items",
    )

    subscription_plan = models.ForeignKey(
        "subscriptions.SubscriptionPlan",
        on_delete=models.PROTECT,
        null=True,
        blank=True,
        related_name="order_items",
    )

    item_description = models.CharField(
        max_length=255,
    )

    quantity = models.PositiveIntegerField(
        default=1,
        validators=[MinValueValidator(1)],
    )

    unit_price = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        validators=[MinValueValidator(Decimal("0.00"))],
    )

    line_total = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=Decimal("0.00"),
        validators=[MinValueValidator(Decimal("0.00"))],
    )

    created_at = models.DateTimeField(
        auto_now_add=True,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    class Meta:
        verbose_name = "Order Item"
        verbose_name_plural = "Order Items"
        ordering = ("created_at",)
        constraints = [
            models.CheckConstraint(
                condition=(
                    models.Q(
                        product__isnull=False,
                        subscription_plan__isnull=True,
                    )
                    | models.Q(
                        product__isnull=True,
                        subscription_plan__isnull=False,
                    )
                ),
                name="order_item_exactly_one_purchase_type",
            ),
            models.CheckConstraint(
                condition=models.Q(quantity__gte=1),
                name="order_item_quantity_at_least_one",
            ),
        ]

    def __str__(self):
        return self.item_description


class OrderNumberCounter(models.Model):
    """
    Stores the next order number to allocate.
    """

    name = models.CharField(
        max_length=50,
        unique=True,
    )

    next_number = models.PositiveBigIntegerField(
        default=1,
    )

    updated_at = models.DateTimeField(
        auto_now=True,
    )

    class Meta:
        verbose_name = "Order Number Counter"
        verbose_name_plural = "Order Number Counters"

    def __str__(self):
        return f"{self.name}: next number {self.next_number}"
